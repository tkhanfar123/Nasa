import type { useNarration } from '../lib/speech';
import { AGE_LABEL } from '../lib/labels';

type N = ReturnType<typeof useNarration>;

export function NarrationControls({ n, age }: { n: N; age: 'primary' | 'secondary' }) {
  const unavailable = n.availability === 'unsupported' || n.availability === 'no-english-voice';
  return (
    <section className="narration" aria-labelledby="narration-title">
      <h2 id="narration-title" className="visually-hidden">Narration controls</h2>
      <div className="narration-buttons" role="group" aria-label="Narration buttons">
        <button type="button" className="btn big" onClick={n.play} disabled={unavailable || n.availability === 'checking' || n.state !== 'idle'}>
          🔊 Listen to my story
        </button>
        <button type="button" className="btn" onClick={n.pause} disabled={n.state !== 'speaking'}>
          ⏸ Pause
        </button>
        <button type="button" className="btn" onClick={n.resume} disabled={n.state !== 'paused'}>
          ▶ Resume
        </button>
        <button type="button" className="btn ghost" onClick={n.stop} disabled={n.state === 'idle'}>
          ⏹ Stop
        </button>
      </div>
      <p className="narration-status" aria-live="polite">
        {n.availability === 'checking' && 'Looking for an English voice in your browser…'}
        {n.availability === 'unsupported' && 'Your browser does not support speech. The full story is written below.'}
        {n.availability === 'no-english-voice' &&
          'No English voice is available in this browser or device, so narration is unavailable. The full story is written below. (You can add a voice in your system settings.)'}
        {n.availability === 'available' && n.state === 'speaking' && `Now reading chapter ${n.currentIndex + 1}…`}
        {n.availability === 'available' && n.state === 'paused' && 'Narration paused.'}
        {n.availability === 'available' && n.state === 'idle' && `Ready. It will read the story for ${AGE_LABEL[age]}.`}
      </p>
      <p className="narration-disclaimer">
        🗣️ The narration is a synthetic voice generated by your browser to read an educational story. It is not a historical recording or the spacecraft's voice.
      </p>
    </section>
  );
}
